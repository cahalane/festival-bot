import { readFileSync, writeFileSync } from "node:fs";
import { loadBundleFrom } from "/home/colm/festival-bot/festivals/ep26/src/lineup.ts";
import { parseGreencopperLineup, greencopperSlugify } from "/home/colm/festival-bot/packages/adapters/src/greencopper.ts";
const T="/home/colm/.claude/jobs/5834c5c1/tmp", R="/home/colm/festival-bot/festivals/ep26";
const blurbs=JSON.parse(readFileSync(`${T}/blurbs.json`,"utf8"));
const mbids=JSON.parse(readFileSync(`${T}/mbids.json`,"utf8"));
const bundle=loadBundleFrom(`${R}/bundle`);
const app=parseGreencopperLineup(bundle);
// extra-sets: the 2 acts the app still lacks
const doc=JSON.parse(readFileSync(`${R}/extra-sets.json`,"utf8"));
const extra=doc.sets.map(s=>({name:s.name,slug:greencopperSlugify(s.name),stage:s.stage,
  start:new Date(s.start),end:new Date(s.end)}));
const all=[...app,...extra];
// stage display names, main arenas first
const disp=new Map();
for(const st of bundle.stages){const n=bundle.strings[st.name]; if(n) disp.set(greencopperSlugify(n.replace(/\s+/g," ").trim()), n.replace(/\s+/g," ").trim());}
const MAIN=["main-stage-presented-by-3","electric-arena","rankins-wood","red-bull-x-terminus","comedy-arena"];
const rank=s=>{const i=MAIN.indexOf(s);return i>=0?i:100;};
const stages=[...new Set(all.map(s=>s.stage))].sort((a,b)=>rank(a)-rank(b)||(disp.get(a)||a).localeCompare(disp.get(b)||b));
const ord=new Map(stages.map((s,i)=>[s,i]));
all.sort((a,b)=>ord.get(a.stage)-ord.get(b.stage)||a.start-b.start);
const fmt=d=>{const p=new Intl.DateTimeFormat("en-GB",{timeZone:"Europe/Dublin",hour12:false,
  year:"numeric",month:"2-digit",day:"2-digit",hour:"2-digit",minute:"2-digit"}).formatToParts(d)
  .reduce((o,x)=>(x.type!=="literal"&&(o[x.type]=x.value),o),{});
  return `${p.year}-${p.month}-${p.day} ${p.hour==="24"?"00":p.hour}:${p.minute}`;};
let nb=0,nm=0;
const lines=all.map(s=>{
  const a={start:fmt(s.start),end:fmt(s.end),stage:disp.get(s.stage)||s.stage,act:s.name};
  const b=blurbs[s.slug]; if(b){a.blurb=b;nb++;}
  const m=mbids[s.name]||mbids[s.name?.toLowerCase()]; if(m){a.mbid=m;nm++;}
  return "act = "+JSON.stringify(a);
});
writeFileSync(`${T}/v42_input1.txt`,lines.join("\r\n"));
writeFileSync(`${T}/v42_input0.txt`,[
 "maintitle = Electric Picnic 2026","timezone = Europe/Dublin","dateFormat = dddd dS mmmm",
 "printAdvisory = 5","daychangeover = 06:00",
 "footer = Source: official Electric Picnic app (Greencopper OTA v42, 24 Aug 2026)",
 "footer = Unofficial test build - generated by festival-bot","lpRevisions","lpComments"].join("\r\n"));
console.log(`acts ${all.length} (app ${app.length} + extra ${extra.length}) | stages ${stages.length} | blurbs ${nb} | mbids ${nm}`);
console.log("first stages:",stages.slice(0,5).map(s=>disp.get(s)||s).join(" | "));
